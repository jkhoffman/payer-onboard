#!/usr/bin/env node
import { parseArgs } from 'node:util';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dedupeClaims, inheritSecurity, linkMembers, reviewCandidates, normalizeClaim, normalizeMember, type Claim, type Fix, type Issue, type Member } from './normalize.ts';
import { writeStore } from './store.ts';
import { DatabaseSync } from 'node:sqlite';
import { scorePayers } from './score.ts';
import { html, markdown } from './report.ts';
import type { Resource } from './fhir-paths.ts';
import { join } from 'node:path';
import { PayerHttp } from './http.ts';
import { authorize, freshToken, listTokens, loadEnv, type StoredToken } from './auth.ts';
import { checkSearches, collectFromFiles, collectLive, profileStats, suggestOverrides, suggestions, type ProbeReport, type Recording } from './probe.ts';
import { scrubRecording } from './scrub.ts';
import { discover, failingGaps, matchVendor, rediscover } from './discover.ts';
import { fetchCapability, fetchSmartConfiguration } from './fhir.ts';
import { ROOT, loadPayer, loadSpec, loadVendors, payerPath, readJson, writeYaml } from './io.ts';
import { resolve } from './layers.ts';
import type { CapabilityStatement, PayerLayer, SmartConfiguration } from './types.ts';

const USAGE = `payer-onboard <command>

  discover <id> --url <base> [--name <name>] [--metadata <file>] [--smart <file>]
      Read the payer's CapabilityStatement (live, or a recorded file) and write payers/<id>.yaml.
  explain <id>
      Show the effective config and which layer (spec, vendor, payer, override) set each value.
  normalize
      Normalize every recording into out/payer-onboard.db: canonical claims and members,
      deterministic member links, duplicate claims, and every fix and issue by named rule.
  score
      Score every payer raw vs normalized (PIQI-inspired) from out/payer-onboard.db and write
      reports/scorecard.{md,html,json}, with points gained attributed to named fix rules.
  accept <id>
      Apply the probe's suggested overrides (search variants, full-sync, client-side filters)
      to payers/<id>.yaml. Suggestions are never applied without this step.
  auth <id> [--member <label>] [--timeout <seconds>]
      SMART authorization-code flow with PKCE using the payer's discovered endpoints; the redirect
      lands on http://localhost:8765/callback. Tokens go to .tokens/<id>/ (gitignored).
  probe <id>
      Fetch claims, patients and coverage through the effective config, record them under
      recordings/<id>/, and test each required search: does the server actually filter?
`;

async function main(argv: string[]): Promise<number> {
  const [command, id, ...rest] = argv;
  const { values } = parseArgs({
    args: rest,
    options: {
      url: { type: 'string' },
      name: { type: 'string' },
      metadata: { type: 'string' },
      smart: { type: 'string' },
      member: { type: 'string' },
      timeout: { type: 'string' },
    },
  });

  if (command === 'discover' && id && values.url) {
    const capability = values.metadata
      ? readJson<CapabilityStatement>(values.metadata)
      : await fetchCapability(values.url);
    const smart = values.smart
      ? readJson<SmartConfiguration>(values.smart)
      : values.metadata
        ? null
        : await fetchSmartConfiguration(values.url);
    const layer = discover({
      id,
      name: values.name ?? id,
      baseUrl: values.url,
      capability,
      smart,
      spec: loadSpec(),
      vendors: loadVendors(),
    });
    const previous = existsSync(payerPath(id)) ? loadPayer(id) : null;
    const { layer: merged, changes } = rediscover(previous, layer);
    writeYaml(payerPath(id), merged, `# GENERATED by \`payer-onboard discover\`. Hand edits go under overrides: and survive rediscovery.`);
    printDiscovery(merged);
    for (const c of changes) console.log(`  change: ${c}`);
    return 0;
  }

  if (command === 'explain' && id) {
    const payer = loadPayer(id);
    const vendors = loadVendors();
    const vendor = matchVendor(payer.discovered.software.name, vendors);
    const eff = resolve(loadSpec(), vendor, payer);
    for (const [path, layer] of Object.entries(eff.provenance).sort()) {
      const value = eff.provenancePaths[path]!.reduce<unknown>((o, k) => (o as Record<string, unknown>)?.[k], eff);
      const shown = JSON.stringify(value) ?? 'undefined';
      console.log(`${path.padEnd(32)} ${(shown.length > 60 ? shown.slice(0, 57) + '...' : shown).padEnd(40)} ← ${layer}`);
    }
    for (const note of vendor?.vendor.notes ?? []) console.log(`note (${vendor!.vendor.id}): ${note}`);
    return 0;
  }

  if (command === 'auth' && id) {
    const payer = loadPayer(id);
    if (payer.auth.mode !== 'smart-app-launch') throw new Error(`${id} needs no auth`);
    const scopes = loadSpec().auth.scopes.filter((s) => payer.auth.mode === 'smart-app-launch' && !payer.auth.missingScopes.includes(s));
    const t = await authorize(payer, values.member ?? 'member1', scopes, 8765, Number(values.timeout ?? 600) * 1000);
    console.log(`Saved token for ${t.member}${t.patient ? ` (patient ${t.patient})` : ''}; expires ${new Date(t.expires_at).toISOString()}; refresh=${Boolean(t.refresh_token)}`);
    return 0;
  }

  if (command === 'probe' && id) {
    const payer = loadPayer(id);
    const spec = loadSpec();
    const vendor = matchVendor(payer.discovered.software.name, loadVendors());
    const eff = resolve(spec, vendor, payer);
    const tokens = payer.auth.mode === 'smart-app-launch' ? listTokens(id) : [];
    const live = payer.auth.mode === 'none' || tokens.length > 0;
    if (!live && !eff.dataSource) throw new Error(`${id} needs OAuth: run \`payer-onboard auth ${id}\` first`);
    const http = live ? new PayerHttp({ rateLimit: eff.rateLimit, retry: eff.retry }) : null;
    if (http) http.origin = new URL(eff.baseUrl).origin;
    let rec: Recording = { ExplanationOfBenefit: [], Patient: [], Coverage: [] };
    let pages = 0;
    if (http && tokens.length === 0) ({ rec, pages } = await collectLive(http, eff));
    const fresh: StoredToken[] = [];
    for (const stored of tokens) {
      const t = await freshToken(payer, stored); // refreshed once; the fresh copy is reused below
      fresh.push(t);
      http!.headers = { authorization: 'Bearer ' + t.access_token };
      const got = await collectLive(http!, eff);
      rec = mergeRecordings(rec, got.rec);
      pages += got.pages;
    }
    if (fresh.length) http!.headers = { authorization: 'Bearer ' + fresh[0]!.access_token };
    if (!http) rec = collectFromFiles(eff.dataSource!.paths, ROOT);
    const searchChecks = await checkSearches(http, eff, payer, spec, rec);
    const base = {
      payer: id,
      source: live ? ('live' as const) : ('recorded-files' as const),
      ...(live ? (tokens.length ? { sourceNote: `${tokens.length} authorized synthetic member(s)` } : {}) : eff.dataSource?.note ? { sourceNote: eff.dataSource.note } : {}),
      recordedAt: new Date().toISOString(),
      counts: { ExplanationOfBenefit: rec.ExplanationOfBenefit.length, Patient: rec.Patient.length, Coverage: rec.Coverage.length },
      ...(rec.stoppedEarly ? { stoppedEarly: rec.stoppedEarly } : {}),
      pages,
      http: http?.stats ?? null,
      profiles: profileStats(rec, spec, payer),
      searchChecks,
    };
    const report: ProbeReport = { ...base, suggestions: suggestions(base, eff), suggestedOverrides: suggestOverrides(searchChecks) };
    const scrubbed = scrubRecording(rec);
    writeRecording(id, scrubbed.rec, { ...report, ...(scrubbed.count ? { scrubbedPatients: scrubbed.count } : {}), ...(scrubbed.unresolved ? { scrubbedUnresolvedClaims: scrubbed.unresolved } : {}) });
    if (scrubbed.count) console.log(`  scrubbed ${scrubbed.count} patient(s) with no synthetic marker before recording`);
    if (scrubbed.unresolved) console.log(`  scrubbed ${scrubbed.unresolved} claim(s) whose patient wasn't recorded or couldn't be resolved (fail closed)`);
    printProbe(report);
    return 0;
  }

  if (command === 'normalize') {
    const spec = loadSpec();
    const vendors = loadVendors();
    const payers = readdirSync(join(ROOT, 'recordings')).filter((d) => existsSync(join(ROOT, 'recordings', d, 'probe.json'))).sort();
    const members: Member[] = [];
    const claims: Claim[] = [];
    const raws = new Map<string, Resource>();
    const fixes: Fix[] = [];
    const issues: Issue[] = [];
    for (const p of payers) {
      const payer = loadPayer(p);
      const eff = resolve(spec, matchVendor(payer.discovered.software.name, vendors), payer);
      const cfg = { ...eff.normalize, specProfiles: (spec.resources['ExplanationOfBenefit']?.profiles ?? []).map((u) => u.split('|')[0]!) };
      for (const r of readNdjson(join(ROOT, 'recordings', p, 'Patient.ndjson'))) members.push(normalizeMember(r, p));
      for (const r of readNdjson(join(ROOT, 'recordings', p, 'ExplanationOfBenefit.ndjson'))) {
        const n = normalizeClaim(r, p, cfg);
        if (raws.has(n.claim.key)) throw new Error(`${p}: resource ${r.id} appears twice in the recording; re-probe`);
        raws.set(n.claim.key, r);
        claims.push(n.claim);
        fixes.push(...n.fixes);
        issues.push(...n.issues);
      }
    }
    const links = linkMembers(members);
    const golden = (k: string | null) => (k ? links.get(k)?.golden ?? k : null);
    const duplicates = dedupeClaims(claims, golden);
    fixes.push(...inheritSecurity(claims, duplicates));
    const review = reviewCandidates(claims, golden, new Set(duplicates.map((d) => d.key)));
    const out = join(ROOT, 'out', 'payer-onboard.db');
    const db = writeStore(out, {
      members: members.map((m) => ({ ...m, ...links.get(m.key)! })),
      claims: claims.map((c) => ({ ...c, goldenMember: golden(c.memberKey), raw: raws.get(c.key) })),
      duplicates,
      review,
      fixes,
      issues,
    });
    console.log(`wrote ${out}`);
    const rows = db.prepare(`
      SELECT c.payer,
        COUNT(*) AS claims,
        (SELECT COUNT(*) FROM unique_claim u WHERE u.payer = c.payer) AS unique_claims,
        (SELECT COUNT(*) FROM duplicate d JOIN claim x ON x.key = d.key WHERE x.payer = c.payer AND d.rule = 'same-claim-id') AS dup_id,
        (SELECT COUNT(*) FROM duplicate d JOIN claim x ON x.key = d.key WHERE x.payer = c.payer AND d.rule = 'fingerprint') AS dup_fp,
        (SELECT COUNT(*) FROM review r JOIN claim x ON x.key = r.key WHERE x.payer = c.payer) AS review,
        (SELECT COUNT(*) FROM member m WHERE m.payer = c.payer) AS members,
        (SELECT COUNT(DISTINCT golden) FROM member m WHERE m.payer = c.payer) AS people
      FROM claim c GROUP BY c.payer ORDER BY c.payer`).all();
    console.table(rows);
    for (const r of db.prepare('SELECT key, candidate_of, reasons FROM review').all() as Array<{ key: string; candidate_of: string; reasons: string }>) {
      console.log(`review: ${r.key} ≈ ${r.candidate_of} (${(JSON.parse(r.reasons) as string[]).join('; ')})`);
    }
    console.log('fixes by rule:');
    console.table(db.prepare(`SELECT substr(key, 1, instr(key, ':') - 1) AS payer, rule, COUNT(*) AS n FROM fix GROUP BY 1, 2 ORDER BY 1, 3 DESC`).all());
    console.log('issues by rule (claims affected):');
    console.table(db.prepare(`SELECT substr(key, 1, instr(key, ':') - 1) AS payer, rule, COUNT(DISTINCT key) AS claims FROM issue GROUP BY 1, 2 ORDER BY 1, 3 DESC`).all());
    return 0;
  }

  if (command === 'score') {
    const dbPath = join(ROOT, 'out', 'payer-onboard.db');
    if (!existsSync(dbPath)) throw new Error('run `payer-onboard normalize` first');
    const db = new DatabaseSync(dbPath, { readOnly: true });
    const spec = loadSpec();
    const vendors = loadVendors();
    const specProfiles = (spec.resources['ExplanationOfBenefit']?.profiles ?? []).map((u) => u.split('|')[0]!);
    const scores = scorePayers(db, (p) => {
      const payer = loadPayer(p);
      return { codeSystemAliases: resolve(spec, matchVendor(payer.discovered.software.name, vendors), payer).normalize.codeSystemAliases, specProfiles };
    });
    const count = (sql: string) => Object.fromEntries((db.prepare(sql).all() as Array<{ payer: string; n: number }>).map((r) => [r.payer, r.n]));
    const sources: Record<string, string> = {};
    for (const s of scores) {
      const probe = readJson<ProbeReport>(join(ROOT, 'recordings', s.payer, 'probe.json'));
      const payer = loadPayer(s.payer);
      sources[s.payer] = `${payer.payer.name} · ${probe.source}${probe.sourceNote ? ` (${probe.sourceNote})` : ''} · recorded ${probe.recordedAt.slice(0, 10)}`;
    }
    const meta = {
      generatedAt: new Date().toISOString().slice(0, 10),
      sources,
      duplicates: count('SELECT c.payer, COUNT(*) n FROM duplicate d JOIN claim c ON c.key = d.key GROUP BY c.payer'),
      review: count('SELECT c.payer, COUNT(*) n FROM review r JOIN claim c ON c.key = r.key GROUP BY c.payer'),
    };
    mkdirSync(join(ROOT, 'reports'), { recursive: true });
    writeFileSync(join(ROOT, 'reports', 'scorecard.json'), JSON.stringify({ meta, scores }, null, 2) + '\n');
    writeFileSync(join(ROOT, 'reports', 'scorecard.md'), markdown(scores, meta) + '\n');
    writeFileSync(join(ROOT, 'reports', 'scorecard.html'), html(scores, meta));
    console.log(markdown(scores, meta));
    // Reconciliation: two independent observers, and the fix log must explain every difference.
    let failed = false;
    for (const s of scores) {
      const r = s.reconciliation;
      const attributed = Object.values(s.gainedBy).reduce((a, b) => a + b, 0);
      const delta = s.normalized.overall - s.raw.overall;
      if (Math.abs(attributed - delta) > 0.3) {
        console.error(`${s.payer}: attributed ${attributed.toFixed(1)} != measured ${delta.toFixed(1)}`);
        failed = true;
      }
      for (const [what, list] of [['unexplained improvement', r.unexplained], ['regression', r.regressions]] as const) {
        if (list.length) {
          failed = true;
          console.error(`${s.payer}: ${list.length} ${what}(s), e.g. ${list.slice(0, 3).map((x) => `${x.key} ${x.check}`).join('; ')}`);
        }
      }
      const one = Object.entries(r.oneSided).map(([k, v]) => `${k} ×${v}`).join(', ');
      if (one) console.log(`${s.payer}: checks observable only after normalization, scored as unchanged (not a gain): ${one}`);
      const idle = Object.entries(r.noScoreEffect).map(([k, v]) => `${k} ×${v}`).join(', ');
      if (idle) console.log(`${s.payer}: logged fixes that moved no check (claim still fails for another reason, or consistency only): ${idle}`);
    }
    if (failed) {
      console.error('\nreconciliation FAILED: the fix log does not explain the measured change');
      return 1;
    }
    console.log('\nreconciliation ✓ raw and normalized observed independently of the fix log; every improvement is explained by a logged fix, no regressions, attribution sums to each change');
    return 0;
  }

  if (command === 'accept' && id) {
    const payer = loadPayer(id);
    const report = readJson<ProbeReport>(join(ROOT, 'recordings', id, 'probe.json'));
    const add = report.suggestedOverrides ?? {};
    if (!Object.keys(add).length) {
      console.log(`${id}: nothing to accept`);
      return 0;
    }
    payer.overrides = { ...(payer.overrides ?? {}), ...add };
    writeYaml(payerPath(id), payer, `# GENERATED by \`payer-onboard discover\`. Hand edits go under overrides: and survive rediscovery.`);
    console.log(`${id}: accepted ${JSON.stringify(add)} from probe of ${report.recordedAt}`);
    return 0;
  }

  process.stderr.write(USAGE);
  return 2;
}

function printDiscovery(p: PayerLayer): void {
  const d = p.discovered;
  console.log(`${p.payer.id}: ${d.software.name} ${d.software.version ?? ''} (FHIR ${d.fhirVersion}) vendor=${d.vendor ?? 'unknown'}`);
  console.log(`  auth: ${p.auth.mode}${p.auth.mode === 'smart-app-launch' ? ` pkce=${p.auth.pkce}` : ''}`);
  console.log(`  declares CARIN profiles: ${d.declaresSpecProfiles ? 'yes' : 'no'}   accepts writes: ${d.writeEnabled ? 'yes (test server)' : 'no'}`);
  const failing = failingGaps(p);
  const byKind = new Map<string, string[]>();
  for (const g of failing) byKind.set(g.kind, [...(byKind.get(g.kind) ?? []), `${g.resource}.${g.kind === 'profile' ? 'profile' : g.name}`]);
  console.log(`  SHALL gaps vs spec: ${failing.length}`);
  for (const [kind, names] of byKind) console.log(`    ${kind}: ${names.join(', ')}`);
  for (const g of p.gaps.filter((x) => x.equivalent)) console.log(`    equivalent available: ${g.resource} search ${g.name} → ${g.equivalent}`);
}

function readNdjson(path: string): Resource[] {
  if (!existsSync(path)) return [];
  return readFileSync(path, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Resource);
}

function mergeRecordings(a: Recording, b: Recording): Recording {
  const out: Recording = { ExplanationOfBenefit: [], Patient: [], Coverage: [] };
  const stopped = a.stoppedEarly ?? b.stoppedEarly;
  if (stopped) out.stoppedEarly = stopped;
  for (const type of ['ExplanationOfBenefit', 'Patient', 'Coverage'] as const) {
    const seen = new Set<string>();
    for (const r of [...a[type], ...b[type]]) {
      const k = r.id ?? JSON.stringify(r);
      if (!seen.has(k)) { seen.add(k); out[type].push(r); }
    }
  }
  return out;
}

function writeRecording(id: string, rec: Recording, report: ProbeReport): void {
  const dir = join(ROOT, 'recordings', id);
  mkdirSync(dir, { recursive: true });
  for (const type of ['ExplanationOfBenefit', 'Patient', 'Coverage'] as const) {
    const resources = rec[type];
    writeFileSync(join(dir, `${type}.ndjson`), resources.map((r: unknown) => JSON.stringify(r)).join('\n') + (resources.length ? '\n' : ''));
  }
  writeFileSync(join(dir, 'probe.json'), JSON.stringify(report, null, 2) + '\n');
}

function printProbe(r: ProbeReport): void {
  const c = r.counts;
  console.log(`${r.payer}: ${r.source}${r.sourceNote ? ` (${r.sourceNote})` : ''}`);
  console.log(`  recorded ${c.ExplanationOfBenefit} claims, ${c.Patient} patients, ${c.Coverage} coverages${r.pages ? ` over ${r.pages} pages` : ''}`);
  if (r.http) console.log(`  http: ${r.http.requests} requests, ${r.http.retries} retries, ${r.http.throttled} throttled, statuses ${JSON.stringify(r.http.statuses)}`);
  console.log(`  CARIN profiles: declared=${r.profiles.declared ? 'yes' : 'no'}, actual ${r.profiles.eobWithSpecProfile}/${r.profiles.eobTotal} claims`);
  console.log('  search (claimed → actual):');
  for (const s of r.searchChecks) console.log(`    ${s.param.padEnd(22)} ${(s.claimed ? 'claimed' : 'not claimed').padEnd(12)} → ${(s.verdict + (s.variant ? ` (${s.variant})` : '')).padEnd(34)} ${s.detail}`);
  for (const s of r.suggestions) console.log(`  • ${s}`);
  if (Object.keys(r.suggestedOverrides).length) console.log(`  suggested overrides (apply with \`accept ${r.payer}\`): ${JSON.stringify(r.suggestedOverrides)}`);
}

loadEnv();
process.exitCode = await main(process.argv.slice(2));
