// Shapes shared across the three config layers.

export type Expectation = 'SHALL' | 'SHOULD' | 'MAY';

export interface SpecResource {
  expectation: Expectation;
  interactions: Record<string, Expectation>;
  search: Record<string, Expectation>;
  profiles: string[];
}

/** Layer 1: what the implementation guide requires. Generated from the IG's own CapabilityStatement. */
export interface SpecLayer {
  spec: { id: string; version: string; source: string };
  resources: Record<string, SpecResource>;
  auth: { mode: 'smart-app-launch'; scopes: string[] };
  /** Default values that no source publishes; probing should confirm or replace them. */
  assumptions: Record<string, string>;
  defaults: {
    rateLimit: { requestsPerSecond: number; burst: number };
    retry: { maxAttempts: number; baseDelayMs: number };
    paging: { style: 'next-link'; pageSize: number };
    probe: { maxClaims: number; maxPatients: number; searchCheckCount: number };
  };
}

/** Layer 2: what a server product does regardless of who runs it. Hand-written, small. */
export interface VendorLayer {
  vendor: { id: string; match: { softwareName: string }; notes?: string[] };
  paging?: { style?: 'next-link'; pageSize?: number };
  rateLimit?: { requestsPerSecond?: number; burst?: number };
  searchDefaults?: Record<string, Record<string, string>>;
  normalize?: {
    codeSystemAliases?: Record<string, string>;
    amountAliases?: { billed?: string[]; paid?: string[] };
  };
}

export interface Gap {
  resource: string;
  kind: 'resource' | 'interaction' | 'search' | 'profile';
  name: string;
  expectation: Expectation;
  /** Set when the server offers an equivalent route, so the gap is reported but not counted as a failure. */
  equivalent?: string;
}

export interface DiscoveredResource {
  interactions: string[];
  search: string[];
  declaredProfiles: string[];
}

/** Layer 3: one payer's endpoint. Generated by `discover`; humans may add overrides. */
export interface PayerLayer {
  payer: { id: string; name: string; baseUrl: string };
  discovered: {
    at: string;
    fhirVersion: string;
    software: { name: string; version?: string };
    vendor: string | null;
    declaresSpecProfiles: boolean;
    writeEnabled: boolean;
  };
  auth:
    | { mode: 'none' }
    | {
        mode: 'smart-app-launch';
        authorizeUrl?: string;
        tokenUrl?: string;
        pkce: boolean;
        missingScopes: string[];
      };
  resources: Record<string, DiscoveredResource>;
  gaps: Gap[];
  overrides?: Record<string, unknown>;
}

export interface CapabilityStatement {
  resourceType: 'CapabilityStatement';
  fhirVersion?: string;
  software?: { name: string; version?: string };
  implementation?: { description?: string; url?: string };
  rest?: Array<{
    mode?: string;
    security?: { service?: Array<{ coding?: Array<{ code?: string }> }> };
    resource?: Array<{
      type: string;
      profile?: string;
      supportedProfile?: string[];
      interaction?: Array<{ code: string; extension?: Ext[] }>;
      searchParam?: Array<{ name: string; extension?: Ext[] }>;
      extension?: Ext[];
    }>;
  }>;
}

export interface Ext {
  url: string;
  valueCode?: string;
}

export interface SmartConfiguration {
  authorization_endpoint?: string;
  token_endpoint?: string;
  scopes_supported?: string[];
  code_challenge_methods_supported?: string[];
}
